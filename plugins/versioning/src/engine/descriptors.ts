import { defineCapabilityDescriptor as descriptor, durableExternal } from "@huhu/kernel";
import { z } from "zod";
import { ConfigureGitAuth, GitAuthSummary } from "./remote-auth.js";
import { SyncConfigPatch, SyncConfigSchema } from "./sync.js";
import { PlanSummarySchema } from "@huhu/contracts";

const Entry = z.object({ id: z.string(), at: z.string(), source: z.string(), title: z.string().nullable(), path: z.string(), size: z.number() });
const Path = z.object({ path: z.string().min(1) });
const Commit = z.object({ id: z.string(), short: z.string(), author: z.string(), at: z.string(), subject: z.string() });
const Status = z.object({ branch: z.string().nullable(), files: z.array(z.object({ path: z.string(), index: z.string(), worktree: z.string(), from: z.string().optional() })) });
const Side = z.object({ exists: z.boolean(), mode: z.string().optional(), size: z.number().optional(), binary: z.boolean().optional(), preview: z.string().optional() });
const Seg = z.union([z.object({ kind: z.literal("common"), text: z.string() }), z.object({ kind: z.literal("conflict"), index: z.number(), base: z.string(), ours: z.string(), theirs: z.string() })]);
const Choice = z.union([z.enum(["ours", "theirs", "both"]), z.object({ custom: z.string().max(10 * 1024 * 1024) })]);
const Repository = z.strictObject({ id: z.string(), head: z.string().nullable(), index: z.string().nullable() });
const SyncTarget = z.strictObject({ repositoryId: z.string(), head: z.string().nullable(), remote: z.string(), branch: z.string(), authRevision: z.uuidv4().nullable() });
const ConflictTarget = z.object({ sessionId: z.string(), localHead: z.string(), remoteHead: z.string() });
const common = { plugin: "versioning", exposable: true, defaultExposed: false } as const;

export const versioningTools = {
  historyTimeline: descriptor({ name: "history.timeline", title: "文件历史", description: "文件历史", ...common, risk: "normal", scope: "read", input: Path, output: z.array(Entry) }),
  historyRead: descriptor({ name: "history.read", title: "历史版本内容", description: "历史版本内容", ...common, risk: "high", scope: "read", input: Path.extend({ entryId: z.string() }), output: z.object({ text: z.string() }) }),
  historyCheckpoint: descriptor({
    name: "history.checkpoint",
    title: "创建文件检查点",
    description: "创建文件检查点",
    ...common,
    risk: "normal",
    ...durableExternal,
    scope: "write",
    input: Path.extend({ title: z.string().min(1).max(80), expectedVersion: z.string().optional() }),
    output: Entry.nullable(),
  }),
  historyRestore: descriptor({
    name: "history.restore",
    title: "恢复文件版本",
    description: "恢复文件版本",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "write",
    input: Path.extend({ entryId: z.string(), expectedCurrentVersion: z.string() }),
    output: z.object({ restored: z.boolean() }),
  }),
  gitStatus: descriptor({
    name: "git.status",
    title: "Git 状态",
    description: "Git 状态",
    ...common,
    risk: "normal",
    scope: "read",
    input: z.object({}),
    output: Status.extend({ isRepo: z.boolean(), installed: z.boolean().default(true), repository: Repository.optional() }),
  }),
  gitInit: descriptor({
    name: "git.init",
    title: "初始化 Vault Git 仓库",
    description: "初始化 Vault Git 仓库",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "admin",
    input: z.object({}),
    output: z.object({ created: z.boolean(), gitignore: z.string() }),
  }),
  gitLog: descriptor({ name: "git.log", title: "Git 提交历史", description: "Git 提交历史", ...common, risk: "normal", scope: "read", input: z.object({ limit: z.number().int().min(1).max(500).default(50) }), output: z.array(Commit) }),
  gitDiff: descriptor({
    name: "git.diff",
    title: "Git 差异",
    description: "Git 差异",
    ...common,
    risk: "high",
    scope: "read",
    input: z.object({ path: z.string().optional(), staged: z.boolean().optional(), commit: z.string().optional() }),
    output: z.object({ diff: z.string() }),
  }),
  gitStage: descriptor({
    name: "git.stage",
    title: "暂存文件",
    description: "暂存文件",
    ...common,
    risk: "normal",
    ...durableExternal,
    scope: "write",
    input: z.object({ paths: z.array(z.string()).min(1), expected: Repository.optional() }),
    output: z.object({ ok: z.literal(true) }),
  }),
  gitUnstage: descriptor({
    name: "git.unstage",
    title: "取消暂存文件",
    description: "取消暂存文件",
    ...common,
    risk: "normal",
    ...durableExternal,
    scope: "write",
    input: z.object({ paths: z.array(z.string()).min(1), expected: Repository.optional() }),
    output: z.object({ ok: z.literal(true) }),
  }),
  gitCommit: descriptor({
    name: "git.commit",
    title: "创建 Git 提交",
    description: "创建 Git 提交",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "write",
    input: z.object({ message: z.string(), expected: Repository.optional() }),
    output: Commit.partial({ subject: true }),
  }),
  syncGet: descriptor({ name: "sync.get", title: "读取同步设置", description: "读取同步设置", ...common, risk: "normal", scope: "read", input: z.object({}),
    output: SyncConfigSchema.extend({ revision: z.string().optional(), periodics: z.object({ pull: PlanSummarySchema.nullable(), sync: PlanSummarySchema.nullable() }).optional() }),
  }),
  syncAuthGet: descriptor({
    name: "sync.auth.get",
    title: "读取 Git 远端认证状态",
    description: "读取 Git 远端认证状态",
    ...common,
    desktopOnly: true,
    risk: "normal",
    scope: "read",
    input: z.object({ remote: z.string().optional() }),
    output: GitAuthSummary,
  }),
  syncAuthConfigure: descriptor({
    name: "sync.auth.configure",
    title: "配置 Git 远端认证",
    description: "配置 Git 远端认证",
    ...common,
    desktopOnly: true,
    risk: "high",
    idempotency: "handler",
    scope: "admin",
    input: ConfigureGitAuth.extend({ operationId: z.uuid().optional() }),
    output: GitAuthSummary,
  }),
  syncUpdate: descriptor({
    name: "sync.update",
    title: "修改同步设置",
    description: "修改同步设置",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "admin",
    input: SyncConfigPatch.extend({ expectedRevision: z.string().optional(), expectedPlans: z.strictObject({ pull: z.string().nullable(), sync: z.string().nullable() }).optional() }),
    output: SyncConfigSchema.extend({ revision: z.string().optional() }),
  }),
  syncPreview: descriptor({
    name: "sync.preview",
    title: "获取远端同步预览",
    description: "获取远端同步预览",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "execute",
    timeoutMs: 120_000,
    input: z.object({ expected: SyncTarget.optional() }),
    output: z.object({ push: z.array(z.string()), skipped: z.array(z.object({ path: z.string(), reason: z.string() })), pull: z.array(z.string()), ahead: z.number(), behind: z.number() }),
  }),
  syncRun: descriptor({
    name: "sync.run",
    title: "同步 Git 远端",
    description: "同步 Git 远端",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "execute",
    timeoutMs: 10 * 60_000,
    input: z.object({ mode: z.enum(["pull", "push", "sync"]).default("sync"), expected: SyncTarget.optional() }),
    output: z.object({ pulled: z.boolean(), pushed: z.boolean(), committed: z.boolean() }),
  }),
  conflictsList: descriptor({
    name: "conflicts.list",
    title: "列出同步冲突",
    description: "列出同步冲突",
    ...common,
    risk: "normal",
    scope: "read",
    input: z.object({}),
    output: z.object({
      conflict: z
        .object({
          id: z.string(),
          createdAt: z.string(),
          localHead: z.string(),
          remoteHead: z.string(),
          files: z.array(z.object({ path: z.string(), kind: z.enum(["blocks", "whole", "unknown"]), blocks: z.number(), reason: z.string().optional() })),
        })
        .nullable(),
    }),
  }),
  conflictsRead: descriptor({
    name: "conflicts.read",
    title: "读取冲突文件",
    description: "读取冲突文件",
    ...common,
    risk: "high",
    scope: "read",
    input: Path.extend({ expected: ConflictTarget.optional() }),
    output: z.union([z.object({ path: z.string(), kind: z.literal("blocks"), segments: z.array(Seg) }), z.object({ path: z.string(), kind: z.literal("whole"), reason: z.string(), ours: Side, theirs: Side })]),
  }),
  conflictsResolve: descriptor({
    name: "conflicts.resolve",
    title: "解决同步冲突",
    description: "解决同步冲突",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "execute",
    timeoutMs: 10 * 60_000,
    input: z.object({
      sessionId: z.string(),
      expected: ConflictTarget.optional(),
      resolutions: z.array(z.union([z.object({ path: z.string(), blocks: z.array(Choice) }), z.object({ path: z.string(), whole: z.enum(["ours", "theirs", "delete"]) })])).min(1),
    }),
    output: z.object({ commit: z.string(), pushed: z.boolean(), syncError: z.string().optional() }),
  }),
  conflictsCancel: descriptor({
    name: "conflicts.cancel",
    title: "取消同步冲突会话",
    description: "取消同步冲突会话",
    ...common,
    risk: "high",
    ...durableExternal,
    scope: "write",
    input: z.object({ expected: ConflictTarget.optional() }),
    output: z.object({ cancelled: z.boolean() }),
  }),
  syncStatus: descriptor({
    name: "sync.status",
    title: "读取同步状态",
    description: "读取同步状态",
    ...common,
    risk: "normal",
    scope: "read",
    input: z.object({}),
    output: z.object({
      name: z.string(),
      detail: z.string(),
      pausedReason: z.enum(["conflict", "auth-failed"]).nullable(),
      authPause: z.object({ source: z.literal("versioning"), target: z.string(), revision: z.uuidv4().nullable(), reason: z.string() }).optional(),
    }),
  }),
};

export const versioningCapabilityDescriptors = Object.values(versioningTools);
